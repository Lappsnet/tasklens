import { NextResponse } from "next/server";
import { requireRole } from "@/lib/auth";
import { getOrCreateHome, listEntries } from "@/lib/passport";
import { makeContractPdf } from "@/lib/pdf";
import { sha256Hex } from "@/lib/contracts";
import { signPhotoUrl } from "@/lib/storage";
import { hasSupabase, serviceClient } from "@/lib/supabase-server";

export const runtime = "nodejs";

/** S3: export the Home Passport as a PDF (for selling/renting the home). */
export async function POST(req: Request) {
  const gate = await requireRole(req, ["customer", "admin"]);
  if ("response" in gate) return gate.response;
  try {
    const home = await getOrCreateHome(gate.session.demo ? undefined : gate.session.userId);
    const entries = await listEntries(home.id);
    const body = entries
      .map(
        (e) =>
          `${e.title} [${e.category}]\nWarranty until: ${e.warranty_until ?? "—"}\nMaterials: ${e.materials.join(", ") || "—"}\n${e.ai_summary}`,
      )
      .join("\n\n---\n\n");
    const buf = makeContractPdf({ title: `Home Passport — ${home.label}`, body, signatures: [], footer: "Generated by TaskLens." });
    const hash = sha256Hex(Buffer.from(buf));
    let download: string | null = null;
    if (hasSupabase()) {
      const db = serviceClient();
      if (db) {
        const path = `passports/${home.id}.pdf`;
        const { error } = await db.storage.from(process.env.STORAGE_BUCKET ?? "media").upload(path, Buffer.from(buf), { contentType: "application/pdf", upsert: true });
        if (!error) download = (await signPhotoUrl(path, 300)) ?? null;
      }
    }
    return NextResponse.json({ sha256: hash, downloadUrl: download, mock: !hasSupabase() });
  } catch (e) {
    console.error("[passport/export] failed:", e instanceof Error ? e.message : e);
    return NextResponse.json({ error: "export_failed" }, { status: 500 });
  }
}
